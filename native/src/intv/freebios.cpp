std::vector<uint8_t> freeGrom() {
  std::vector<uint8_t> g(2048, 0);
  for (int c = 0; c < 95; c++)
    for (int y = 0; y < 7; y++) g[c * 8 + y] = static_cast<uint8_t>(FONT[c][y] << 2);  // colunas 1..5
  // cartões 95..: alguns blocos simples (cheio, metades, xadrez) para jogos que desenham com a GROM
  for (int y = 0; y < 8; y++) {
    g[95 * 8 + y] = 0xFF;
    g[96 * 8 + y] = y < 4 ? 0xFF : 0x00;
    g[97 * 8 + y] = 0xF0;
    g[98 * 8 + y] = (y & 1) ? 0x55 : 0xAA;
  }
  return g;
}

